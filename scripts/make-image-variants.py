#!/usr/bin/env python3
"""Smaller copies of large public images for phones (performance pass 2026-10-27).

For every /public/images/**/*.webp|jpg wider than 900px (og/ share cards
excluded) this writes <name>.640.webp and, when the original is wider than
1300px, <name>.1024.webp next to it, then rewrites app/utils/imageVariants.ts
(the manifest imgSet() reads). Re-run after adding or replacing a large image:

    python scripts/make-image-variants.py
"""
import json
import os
from PIL import Image

ROOT = os.path.join(os.path.dirname(__file__), '..')
PUB = os.path.join(ROOT, 'public')
manifest = {}
for base, _, files in os.walk(os.path.join(PUB, 'images')):
    if os.sep + 'og' in base:
        continue
    for f in sorted(files):
        if not f.lower().endswith(('.webp', '.jpg', '.jpeg', '.png')) or '.640.' in f or '.1024.' in f:
            continue
        path = os.path.join(base, f)
        im = Image.open(path)
        w, h = im.size
        if w <= 900:
            continue
        stem = path.rsplit('.', 1)[0]
        widths = [640] + ([1024] if w > 1300 else [])
        for tw in widths:
            out = f'{stem}.{tw}.webp'
            th = round(h * tw / w)
            img = im.convert('RGBA' if im.mode in ('RGBA', 'LA', 'P') else 'RGB').resize((tw, th), Image.LANCZOS)
            img.save(out, 'WEBP', quality=78, method=6)
        url = '/' + os.path.relpath(path, PUB).replace(os.sep, '/')
        manifest[url] = {'w': w, 'variants': widths}

lines = ',\n'.join(f"  {json.dumps(k)}: {{ w: {v['w']}, variants: {json.dumps(v['variants'])} }}" for k, v in sorted(manifest.items()))
ts = (
    "// GENERATED by scripts/make-image-variants.py — do not edit by hand.\n"
    "// Large public images that have smaller copies (<name>.640.webp,\n"
    "// <name>.1024.webp) for phones; read by imgSet() in app/utils/imgSet.ts.\n"
    "export const IMAGE_VARIANTS: Record<string, { w: number; variants: number[] }> = {\n"
    f"{lines}\n}}\n"
)
with open(os.path.join(ROOT, 'app', 'utils', 'imageVariants.ts'), 'w', encoding='utf-8', newline='\n') as fh:
    fh.write(ts)
print(f'{len(manifest)} images with variants')
